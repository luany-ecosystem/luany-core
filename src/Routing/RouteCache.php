<?php

namespace Luany\Core\Routing;

/**
 * RouteCache
 *
 * Serializes and loads the compiled route table to/from a PHP file,
 * eliminating the need to re-execute routes/http.php on every request.
 *
 * Only routes with array actions ([Controller::class, 'method']) are stored.
 * Closure actions cannot be serialized and are silently excluded — this is
 * intentional. In production, all routes should use controller array syntax.
 *
 * Cache file format:
 *   A plain PHP file that returns an array:
 *   <?php return ['routes' => [...], 'named' => [...]];
 *
 * Workflow:
 *   // Production bootstrap (public/index.php or Kernel::boot()):
 *   if (!Route::loadCache(base_path('storage/cache/routes.php'))) {
 *       require base_path('routes/http.php');
 *       Route::cache(base_path('storage/cache/routes.php'));
 *   }
 *
 *   // Deployment / CI (after deploying new code):
 *   @unlink(base_path('storage/cache/routes.php'));
 *   // Or: luany route:cache (Phase 6 CLI command)
 */
class RouteCache
{
    /**
     * Serialize the route table to a PHP file.
     *
     * Every route action and middleware must survive var_export(): closures
     * and objects without __set_state() make this method throw, listing the
     * offending routes, instead of silently dropping them.
     *
     * @param array<int, array<string, mixed>> $routes        The Router's $routes array
     * @param array<string, string>             $namedRoutes   The Router's $namedRoutes array
     * @param string                            $path          Absolute path to write the cache file
     * @param array<string, class-string>       $modelBindings Route::model() bindings
     *
     * @throws \RuntimeException If a route is not cacheable or the file cannot be written
     */
    public static function store(array $routes, array $namedRoutes, string $path, array $modelBindings = []): void
    {
        $dir = dirname($path);
        if (!is_dir($dir) && !mkdir($dir, 0755, true) && !is_dir($dir)) {
            throw new \RuntimeException("Route cache directory could not be created: {$dir}");
        }

        $problems = [];

        foreach ($routes as $route) {
            $label = ($route['method'] ?? '?') . ' ' . ($route['uri'] ?? '?');

            if (!self::isExportable($route['action'])) {
                $problems[] = "{$label}: closure actions cannot be cached — use [Controller::class, 'method'] or Route::view()";
            }

            foreach ((array) ($route['middleware'] ?? []) as $middleware) {
                if (!self::isExportable($middleware)) {
                    $type = is_object($middleware) ? get_class($middleware) : gettype($middleware);
                    $problems[] = "{$label}: middleware [{$type}] cannot be cached — register it by class name or implement __set_state()";
                }
            }
        }

        if ($problems !== []) {
            throw new \RuntimeException(
                "Routes cannot be cached:\n  - " . implode("\n  - ", $problems)
            );
        }

        $export  = var_export([
            'routes' => array_values($routes),
            'named'  => $namedRoutes,
            'models' => $modelBindings,
        ], true);
        $content = "<?php\n\n// Generated by luany/core RouteCache — do not edit manually.\n// Delete this file to force re-generation.\n\nreturn {$export};\n";

        // Atomic write: concurrent requests never include a half-written file.
        $tmp = $path . '.' . bin2hex(random_bytes(6)) . '.tmp';
        if (file_put_contents($tmp, $content, LOCK_EX) === false || !rename($tmp, $path)) {
            @unlink($tmp);
            throw new \RuntimeException("Failed to write route cache file: {$path}");
        }

        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($path, true);
        }
    }

    /**
     * Whether a value survives var_export() + include.
     */
    private static function isExportable(mixed $value): bool
    {
        if ($value instanceof \Closure) {
            return false;
        }

        if (is_object($value)) {
            return method_exists($value, '__set_state');
        }

        if (is_array($value)) {
            foreach ($value as $item) {
                if (!self::isExportable($item)) {
                    return false;
                }
            }
        }

        return !is_resource($value);
    }

    /**
     * Load a previously cached route table.
     *
     * Returns null if the cache file does not exist or cannot be read.
     * The caller is responsible for falling back to executing routes/http.php.
     *
     * @param  string  $path  Absolute path to the cache file
     * @return array{routes: array, named: array}|null
     */
    /** @return array{routes: array<int, array<string, mixed>>, named: array<string, string>, models?: array<string, class-string>}|null */
    public static function load(string $path): ?array
    {
        if (!file_exists($path) || !is_readable($path)) {
            return null;
        }

        $data = include $path;

        if (!is_array($data) || !isset($data['routes'], $data['named'])) {
            return null;
        }

        return $data;
    }

    /**
     * Delete the cache file.
     *
     * @param string $path Absolute path to the cache file
     */
    public static function clear(string $path): void
    {
        if (file_exists($path)) {
            @unlink($path);
        }
    }
}
